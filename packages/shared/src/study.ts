import { z } from 'zod'
import { cardStateSchema, ratingSchema } from './srs.ts'

export const cardModeSchema = z.enum(['RECOGNIZE', 'LISTEN_TYPE'])
export type CardMode = z.infer<typeof cardModeSchema>

export const studyCardSchema = z.object({
  cardId: z.string(),
  mode: cardModeSchema,
  /** True for a card that has never been reviewed. */
  isNew: z.boolean(),
  state: cardStateSchema,
  word: z.object({
    id: z.string(),
    lemma: z.string(),
    pos: z.string().nullable(),
    ipa: z.string().nullable(),
    meaningVi: z.string(),
    audioUrl: z.string().nullable(),
    examples: z.array(
      z.object({
        id: z.string(),
        textEn: z.string(),
        textVi: z.string(),
        audioUrl: z.string().nullable(),
      }),
    ),
  }),
})
export type StudyCard = z.infer<typeof studyCardSchema>

export const studyTodayResponseSchema = z.object({
  /** Due cards first (earliest due first), then new cards by TSL rank. */
  cards: z.array(studyCardSchema),
  dueCount: z.number(),
  newCount: z.number(),
  /** When the user's current day ends; cards due before this are still part of today. */
  dayEndsAt: z.iso.datetime(),
})
export type StudyTodayResponse = z.infer<typeof studyTodayResponseSchema>

export const reviewInputSchema = z.object({
  /** Generated by the client, so a retried request is not applied twice. */
  id: z.uuid(),
  cardId: z.string().min(1),
  rating: ratingSchema,
  /** When the user rated the card, on the client's clock. */
  reviewedAt: z.iso.datetime(),
})
export type ReviewInput = z.infer<typeof reviewInputSchema>

export const reviewBatchRequestSchema = z.object({
  reviews: z.array(reviewInputSchema).min(1).max(500),
})
export type ReviewBatchRequest = z.infer<typeof reviewBatchRequestSchema>

export const reviewBatchResponseSchema = z.object({
  applied: z.number(),
  duplicates: z.number(),
  /** Ids of reviews whose card does not exist or belongs to someone else. */
  rejected: z.array(z.string()),
  /** New state of every card the batch changed. */
  cards: z.array(z.object({ cardId: z.string(), state: cardStateSchema })),
})
export type ReviewBatchResponse = z.infer<typeof reviewBatchResponseSchema>
